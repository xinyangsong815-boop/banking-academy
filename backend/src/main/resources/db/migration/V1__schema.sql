CREATE TABLE staff_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(60) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','TELLER','AUDITOR')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE auth_session (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES staff_user(id),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_session_expiry ON auth_session(expires_at);
CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(120) NOT NULL,
    risk_level VARCHAR(12) NOT NULL CHECK (risk_level IN ('LOW','MEDIUM','HIGH')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE bank_account (
    id VARCHAR(36) PRIMARY KEY,
    account_no VARCHAR(24) NOT NULL UNIQUE,
    customer_id BIGINT REFERENCES customer(id),
    name VARCHAR(60) NOT NULL,
    balance DECIMAL(18,2) NOT NULL DEFAULT 0,
    status VARCHAR(12) NOT NULL CHECK (status IN ('ACTIVE','FROZEN','CLOSED')),
    internal_account BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (internal_account OR balance >= 0)
);
CREATE INDEX idx_account_customer ON bank_account(customer_id);
CREATE TABLE booking (
    id VARCHAR(36) PRIMARY KEY,
    business_key VARCHAR(100) NOT NULL UNIQUE,
    kind VARCHAR(24) NOT NULL,
    description VARCHAR(160) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE ledger_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id VARCHAR(36) NOT NULL REFERENCES booking(id),
    account_id VARCHAR(36) NOT NULL REFERENCES bank_account(id),
    amount DECIMAL(18,2) NOT NULL CHECK (amount <> 0),
    balance_after DECIMAL(18,2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (booking_id, account_id)
);
CREATE INDEX idx_ledger_account ON ledger_entry(account_id, id);
CREATE TABLE transfer_order (
    id VARCHAR(36) PRIMARY KEY,
    source_id VARCHAR(36) NOT NULL REFERENCES bank_account(id),
    target_id VARCHAR(36) NOT NULL REFERENCES bank_account(id),
    amount DECIMAL(18,2) NOT NULL CHECK (amount > 0),
    fee DECIMAL(18,2) NOT NULL CHECK (fee >= 0),
    channel VARCHAR(12) NOT NULL,
    remark VARCHAR(120) NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES staff_user(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (source_id <> target_id)
);
CREATE INDEX idx_transfer_daily ON transfer_order(source_id, created_at);
CREATE TABLE idempotent_request (
    scope VARCHAR(100) NOT NULL,
    request_key VARCHAR(64) NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    response_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (scope, request_key)
);
CREATE TABLE loan_application (
    id VARCHAR(36) PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(id),
    account_id VARCHAR(36) NOT NULL REFERENCES bank_account(id),
    principal DECIMAL(18,2) NOT NULL CHECK (principal > 0),
    months INTEGER NOT NULL CHECK (months BETWEEN 1 AND 60),
    annual_rate DECIMAL(8,6) NOT NULL,
    repayment_method VARCHAR(24) NOT NULL,
    purpose VARCHAR(160) NOT NULL,
    state VARCHAR(20) NOT NULL,
    applicant_id BIGINT NOT NULL REFERENCES staff_user(id),
    reviewer_id BIGINT REFERENCES staff_user(id),
    review_note VARCHAR(200),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE repayment_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id VARCHAR(36) NOT NULL REFERENCES loan_application(id),
    period_no INTEGER NOT NULL,
    due_date DATE NOT NULL,
    principal DECIMAL(18,2) NOT NULL,
    interest DECIMAL(18,2) NOT NULL,
    UNIQUE (loan_id, period_no)
);
CREATE TABLE financial_product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(300) NOT NULL,
    risk_level VARCHAR(12) NOT NULL,
    annual_rate DECIMAL(8,6) NOT NULL,
    minimum_amount DECIMAL(18,2) NOT NULL,
    remaining_quota DECIMAL(18,2) NOT NULL CHECK (remaining_quota >= 0),
    duration_days INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE product_subscription (
    id VARCHAR(36) PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES financial_product(id),
    account_id VARCHAR(36) NOT NULL REFERENCES bank_account(id),
    amount DECIMAL(18,2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES staff_user(id),
    title VARCHAR(100) NOT NULL,
    content VARCHAR(500) NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_notification_user ON notification(user_id, id);
CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(40) NOT NULL,
    action VARCHAR(80) NOT NULL,
    trace_id VARCHAR(36),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
